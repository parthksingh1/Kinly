"""Access to the shared Kinly database.

The schema is owned by Prisma (family-app/prisma/schema.prisma). `schema.sql` next to
this file is generated from it, so the Python side can create a fresh database on its
own (tests, first boot) without drifting from the family app.

Conventions that must match Prisma on SQLite:
- ids are generated by the writer (we use uuid4 hex; Prisma uses cuid, both are strings)
- DateTime columns store unix epoch milliseconds (integers)
- booleans are 0/1, `@updatedAt` columns are written explicitly
"""

from __future__ import annotations

import json
import sqlite3
import threading
import uuid
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Optional

from loguru import logger

from .settings import settings

SCHEMA_SQL = Path(__file__).with_name("schema.sql")

_lock = threading.RLock()
_conn: Optional[sqlite3.Connection] = None


def new_id() -> str:
    return "k" + uuid.uuid4().hex[:24]


def now_utc() -> datetime:
    return datetime.now(timezone.utc)


def to_db_dt(value: Optional[datetime]) -> Optional[int]:
    if value is None:
        return None
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return int(value.timestamp() * 1000)


def from_db_dt(value: Any) -> Optional[datetime]:
    """Prisma writes integers (ms); SQL defaults may write text. Accept both."""
    if value is None or value == "":
        return None
    if isinstance(value, (int, float)):
        return datetime.fromtimestamp(value / 1000, tz=timezone.utc)
    text = str(value).strip()
    if text.isdigit():
        return datetime.fromtimestamp(int(text) / 1000, tz=timezone.utc)
    text = text.replace("Z", "+00:00").replace(" ", "T", 1)
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def _connect() -> sqlite3.Connection:
    path = settings.database_path
    path.parent.mkdir(parents=True, exist_ok=True)
    fresh = not path.exists() or path.stat().st_size == 0
    conn = sqlite3.connect(str(path), check_same_thread=False, isolation_level=None)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA busy_timeout=5000")
    conn.execute("PRAGMA foreign_keys=ON")
    has_tables = conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='elders'"
    ).fetchone()
    if fresh or not has_tables:
        logger.info(f"Creating Kinly database schema at {path}")
        conn.executescript(SCHEMA_SQL.read_text(encoding="utf-8"))
    return conn


def conn() -> sqlite3.Connection:
    global _conn
    with _lock:
        if _conn is None:
            _conn = _connect()
        return _conn


def reset_connection() -> None:
    """Used by tests after pointing settings.database_path somewhere else."""
    global _conn
    with _lock:
        if _conn is not None:
            _conn.close()
        _conn = None


@contextmanager
def transaction():
    c = conn()
    with _lock:
        c.execute("BEGIN IMMEDIATE")
        try:
            yield c
            c.execute("COMMIT")
        except Exception:
            c.execute("ROLLBACK")
            raise


def _encode(value: Any) -> Any:
    if isinstance(value, datetime):
        return to_db_dt(value)
    if isinstance(value, bool):
        return 1 if value else 0
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)
    return value


def query(sql: str, params: Iterable[Any] = ()) -> list[dict]:
    with _lock:
        rows = conn().execute(sql, [_encode(p) for p in params]).fetchall()
    return [dict(r) for r in rows]


def query_one(sql: str, params: Iterable[Any] = ()) -> Optional[dict]:
    rows = query(sql, params)
    return rows[0] if rows else None


def execute(sql: str, params: Iterable[Any] = ()) -> int:
    with _lock:
        cur = conn().execute(sql, [_encode(p) for p in params])
        return cur.rowcount


# Tables whose Prisma model has @updatedAt
_UPDATED_AT_TABLES = {"elders", "daily_summaries", "phone_calls"}


def insert(table: str, data: dict) -> dict:
    row = dict(data)
    row.setdefault("id", new_id())
    now = now_utc()
    row.setdefault("createdAt", now)
    if table in _UPDATED_AT_TABLES:
        row.setdefault("updatedAt", now)
    cols = ", ".join(f'"{k}"' for k in row)
    marks = ", ".join("?" for _ in row)
    execute(f'INSERT INTO "{table}" ({cols}) VALUES ({marks})', row.values())
    return row


def update(table: str, row_id: str, data: dict) -> None:
    if not data:
        return
    values = dict(data)
    if table in _UPDATED_AT_TABLES:
        values.setdefault("updatedAt", now_utc())
    sets = ", ".join(f'"{k}" = ?' for k in values)
    execute(f'UPDATE "{table}" SET {sets} WHERE id = ?', [*values.values(), row_id])


def get(table: str, row_id: str) -> Optional[dict]:
    return query_one(f'SELECT * FROM "{table}" WHERE id = ?', [row_id])


def loads(value: Any, default: Any) -> Any:
    if value in (None, ""):
        return default
    try:
        return json.loads(value)
    except (TypeError, json.JSONDecodeError):
        return default
